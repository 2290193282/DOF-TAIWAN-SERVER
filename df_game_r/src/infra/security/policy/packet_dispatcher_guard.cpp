// IDA_EA: 0x859092A
// IDA_NAME: _Z10DenyPacketi
// DEMANGLED: DenyPacket(int)
int DenyPacket(int packet_type) {
    for (unsigned int index = 0;
         index < sizeof(kDenyPacketOrder) / sizeof(kDenyPacketOrder[0]);
         ++index) {
        if (packet_type == kDenyPacketOrder[index]) {
            return 1;
        }
    }
    return 0;
}
