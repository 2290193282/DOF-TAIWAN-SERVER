#ifndef OLDSRV_SECURITY_CRYPTO_TYPES_H_
#define OLDSRV_SECURITY_CRYPTO_TYPES_H_


// IDA: GetCryptoType @0x8097160 returns sequence % 14. The numeric order is
// the original df_game_r crypto graph table order and must not be changed.
enum CRYPTO_GRAPH_TYPE {
    CRYPTO_GRAPH_SHIFT = 0,
    CRYPTO_GRAPH_RIJNDAEL = 1,
    CRYPTO_GRAPH_BLOWFISH = 2,
    CRYPTO_GRAPH_RC6 = 3,
    CRYPTO_GRAPH_TWOFISH = 4,
    CRYPTO_GRAPH_TEA = 5,
    CRYPTO_GRAPH_KASUMI = 6,
    CRYPTO_GRAPH_XTEA = 7,
    CRYPTO_GRAPH_NOEKEON = 8,
    CRYPTO_GRAPH_KHAZAD = 9,
    CRYPTO_GRAPH_CAST5 = 10,
    CRYPTO_GRAPH_SKIPJACK = 11,
    CRYPTO_GRAPH_MULTI2 = 12,
    CRYPTO_GRAPH_ANUBIS = 13,
};

// IDA mode constants used by ICryptoGraph::SetMode wrappers.
enum CRYPTO_MODE_TYPE {
    CRYPTO_MODE_ECB = 0,
    CRYPTO_MODE_CBC = 1,
    CRYPTO_MODE_CFB = 2,
    CRYPTO_MODE_OFB = 3,
};

// IDA crypto return values observed from the 14 graph wrappers.
enum CRYPTO_RESULT {
    CRYPTO_RESULT_OK = 0x6FFFFFFF,
    CRYPTO_RESULT_ERROR = 0x70000000,
    CRYPTO_RESULT_NULL_KEY = 0x70000001,
    CRYPTO_RESULT_INVALID_KEY_SIZE = 0x70000002,
    CRYPTO_RESULT_INVALID_MODE = 0x70000003,
    CRYPTO_RESULT_INVALID_PADDING = 0x70000004,
    CRYPTO_RESULT_NOT_INITIALIZED = 0x70000005,
    CRYPTO_RESULT_INVALID_BLOCK_SIZE = 0x70000006,
    CRYPTO_RESULT_BUFFER_TOO_SMALL = 0x7000000A,
    CRYPTO_RESULT_INVALID_LENGTH = 0x7000000B,
    CRYPTO_RESULT_NO_CONTEXT = 0x7000000C,
    CRYPTO_RESULT_UNSUPPORTED = 0x70000017,
    CRYPTO_RESULT_INVALID_ROUNDS = 0x7000001A,
};


#endif  // OLDSRV_SECURITY_CRYPTO_TYPES_H_
